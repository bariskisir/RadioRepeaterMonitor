export const TR_TALKGROUP_IDS = TR_TALKGROUPS.map((talkgroup) => talkgroup.id)

const talkgroupById = new Map(TR_TALKGROUPS.map((talkgroup) => [talkgroup.id, talkgroup]))

export function findTalkgroup(id: number): TalkgroupInfo | undefined {
  return talkgroupById.get(id)
}

export function getTalkgroupLabel(id: number | null): string {
  if (id === null) {
    return 'TG ?'
  }
  const talkgroup = talkgroupById.get(id)
  return talkgroup ? `TG ${id} · ${talkgroup.name}` : `TG ${id}`
}

export function getTalkgroupName(id: number | null): string {
  if (id === null) {
    return 'Bilinmeyen talkgroup'
  }
  return talkgroupById.get(id)?.name ?? `TG ${id}`
}

export function getRegionTitleKey(region: TalkgroupRegionId): string {
  return (
    TALKGROUP_REGIONS.find((candidate) => candidate.id === region)?.titleKey ??
    'radio.regions.general'
  )
}

export function getTalkgroupsByRegion(region: TalkgroupRegionId): readonly TalkgroupInfo[] {
  return TR_TALKGROUPS.filter((talkgroup) => talkgroup.region === region)
}

export function getRepeaterCities(): readonly string[] {
  return Array.from(new Set(TR_REPEATERS.map((repeater) => repeater.city))).sort((left, right) =>
    left.localeCompare(right, 'tr'),
  )
}

export function getRepeaterCityRegion(city: string): TalkgroupRegionId {
  return TR_REPEATERS.find((repeater) => repeater.city === city)?.region ?? 'general'
}

export function getRepeatersByRegion(region: TalkgroupRegionId): readonly RepeaterInfo[] {
  return TR_REPEATERS.filter((repeater) => repeater.region === region)
}
